function getCompatibilityTags(characterId) {
  const c = CHARACTER_DB[characterId];
  if (!c) return null;
  const toTags = ids => (ids || []).map(id => ({ id, name: (CHARACTER_DB[id] && CHARACTER_DB[id].name) || id }));
  return {
    good: toTags(c.compatibleTypes),
    spark: toTags(c.sparkTypes),
    clash: toTags(c.frictionTypes),
  };
}

// 서버 API가 반환하는 카탈로그 전체 — js/character-api.js가 클라이언트 캐시(js/character/character-db.js)
// 에 그대로 병합한다. 각 레코드에 illustration(이미지 경로)·compatTags(good/spark/clash 이름 목록)를
// 미리 붙여서 내려보내, 클라이언트가 별도 조회 없이 렌더링만 하면 되게 한다.
function buildCatalog() {
  const records = {};
  Object.keys(CHARACTER_DB).forEach(id => {
    records[id] = Object.assign({}, CHARACTER_DB[id], {
      illustration: getCharacterIllustration(id),
      compatTags: getCompatibilityTags(id),
    });
  });
  return records;
}

module.exports = {
  CHARACTER_DB, CHARACTER_ILLUSTRATION, CHARACTER_ILLUSTRATION_FALLBACK,
  getCharacterIllustration, getCompatibilityTags, buildCatalog,
};
